CREATE TABLE categorias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL UNIQUE,
  descripcion VARCHAR(250)
);
CREATE TABLE cursos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo VARCHAR(150) NOT NULL,
  descripcion VARCHAR(1000) NOT NULL,
  tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('GRATUITO','PAGO')),
  precio NUMERIC(10,2) NOT NULL CHECK (precio >= 0),
  docente_id BIGINT NOT NULL,
  estado VARCHAR(25) NOT NULL,
  categoria_id BIGINT NOT NULL REFERENCES categorias(id),
  fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE modulos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  curso_id BIGINT NOT NULL REFERENCES cursos(id) ON DELETE CASCADE,
  titulo VARCHAR(150) NOT NULL,
  orden_modulo INTEGER NOT NULL
);
CREATE TABLE lecciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  modulo_id BIGINT NOT NULL REFERENCES modulos(id) ON DELETE CASCADE,
  titulo VARCHAR(150) NOT NULL,
  orden_leccion INTEGER NOT NULL,
  url_contenido VARCHAR(500)
);
