CREATE TABLE asistencias (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 inscripcion_id BIGINT NOT NULL REFERENCES inscripciones(id) ON DELETE CASCADE,
 fecha_clase DATE NOT NULL,
 estado VARCHAR(12) NOT NULL CHECK(estado IN ('PRESENTE','TARDE','FALTA','JUSTIFICADA')),
 observacion VARCHAR(300), fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uk_asistencia_fecha UNIQUE(inscripcion_id,fecha_clase)
);
CREATE TABLE certificados (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 inscripcion_id BIGINT NOT NULL UNIQUE REFERENCES inscripciones(id) ON DELETE CASCADE,
 codigo VARCHAR(80) NOT NULL UNIQUE,
 estado VARCHAR(20) NOT NULL,
 costo NUMERIC(10,2) NOT NULL DEFAULT 0,
 pago_confirmado BOOLEAN NOT NULL DEFAULT FALSE,
 fecha_emision TIMESTAMP
);
