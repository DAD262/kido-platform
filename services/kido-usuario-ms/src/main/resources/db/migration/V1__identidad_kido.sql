-- Perfil KIDO de cada cuenta de Keycloak. Su id numérico es el que usan
-- cursos, inscripciones y pagos como docenteId / estudianteId.
CREATE TABLE perfiles (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2001) PRIMARY KEY,
    keycloak_id        VARCHAR(64) UNIQUE,
    username           VARCHAR(160) NOT NULL UNIQUE,
    email              VARCHAR(160) UNIQUE,
    nombres            VARCHAR(80)  NOT NULL,
    apellidos          VARCHAR(80)  NOT NULL,
    tipo_registro      VARCHAR(20)  NOT NULL,
    docente_verificado BOOLEAN      NOT NULL DEFAULT FALSE,
    creado_en          TIMESTAMP    NOT NULL,
    actualizado_en     TIMESTAMP    NOT NULL,
    CONSTRAINT ck_perfil_tipo CHECK (tipo_registro IN ('ESTUDIANTE', 'DOCENTE'))
);

-- Datos que un docente entrega para que administración verifique su identidad y trayectoria.
CREATE TABLE solicitudes_docente (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfil_id            BIGINT       NOT NULL UNIQUE REFERENCES perfiles (id),
    dni                  VARCHAR(8)   NOT NULL,
    telefono             VARCHAR(15)  NOT NULL,
    grado_academico      VARCHAR(20)  NOT NULL,
    especialidad         VARCHAR(120) NOT NULL,
    institucion          VARCHAR(160) NOT NULL,
    anios_experiencia    INTEGER      NOT NULL,
    enlace_profesional   VARCHAR(300),
    presentacion         VARCHAR(1200) NOT NULL,
    declaracion_aceptada BOOLEAN      NOT NULL,
    estado               VARCHAR(20)  NOT NULL,
    comentario_revision  VARCHAR(600),
    revisado_por         VARCHAR(160),
    revisado_en          TIMESTAMP,
    enviado_en           TIMESTAMP    NOT NULL,
    intentos             INTEGER      NOT NULL DEFAULT 1,
    CONSTRAINT ck_solicitud_estado CHECK (estado IN ('PENDIENTE', 'OBSERVADA', 'APROBADA', 'RECHAZADA')),
    CONSTRAINT ck_solicitud_grado CHECK (grado_academico IN ('TECNICO', 'BACHILLER', 'TITULADO', 'MAGISTER', 'DOCTOR')),
    CONSTRAINT ck_solicitud_experiencia CHECK (anios_experiencia BETWEEN 0 AND 60)
);
CREATE INDEX idx_solicitud_estado ON solicitudes_docente (estado, enviado_en);
CREATE UNIQUE INDEX uk_solicitud_dni_activa ON solicitudes_docente (dni) WHERE estado <> 'RECHAZADA';

-- El PDF de sustento (CV, título o constancia) se guarda aparte para no cargarlo en cada listado.
CREATE TABLE documentos_solicitud (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id BIGINT       NOT NULL UNIQUE REFERENCES solicitudes_docente (id) ON DELETE CASCADE,
    nombre       VARCHAR(160) NOT NULL,
    tipo         VARCHAR(80)  NOT NULL,
    tamano       BIGINT       NOT NULL,
    contenido    BYTEA        NOT NULL,
    subido_en    TIMESTAMP    NOT NULL
);
