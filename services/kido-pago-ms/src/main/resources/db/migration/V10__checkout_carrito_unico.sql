CREATE TABLE compras_carrito (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 estudiante_id BIGINT NOT NULL,
 ambiente VARCHAR(20) NOT NULL DEFAULT 'DESCONOCIDO', receptor_mp VARCHAR(40) NOT NULL,
 total NUMERIC(10,2) NOT NULL CHECK(total>0), huella VARCHAR(64) NOT NULL,
 estado VARCHAR(24) NOT NULL, fecha_creacion TIMESTAMP NOT NULL,
 mp_preference_id VARCHAR(120), mp_payment_id VARCHAR(120) UNIQUE,
 checkout_url VARCHAR(1500), retorno_configurado BOOLEAN NOT NULL DEFAULT FALSE,
 pagos_aprobados_detectados INTEGER NOT NULL DEFAULT 0,
 UNIQUE(id,mp_payment_id)
);
ALTER TABLE ordenes_compra ADD COLUMN compra_carrito_id BIGINT REFERENCES compras_carrito(id);
ALTER TABLE ordenes_compra DROP CONSTRAINT ordenes_compra_mp_payment_id_key;
CREATE UNIQUE INDEX uk_pago_individual ON ordenes_compra(mp_payment_id) WHERE compra_carrito_id IS NULL;
CREATE UNIQUE INDEX uk_curso_compra_carrito ON ordenes_compra(compra_carrito_id,curso_id) WHERE compra_carrito_id IS NOT NULL;
ALTER TABLE ordenes_compra ADD CONSTRAINT fk_pago_agrupado FOREIGN KEY(compra_carrito_id,mp_payment_id) REFERENCES compras_carrito(id,mp_payment_id);
CREATE INDEX idx_lineas_carrito ON ordenes_compra(compra_carrito_id);
ALTER TABLE constancias_compra ALTER COLUMN curso_titulo TYPE TEXT;
ALTER TABLE constancias_compra ADD COLUMN compra_carrito_id BIGINT REFERENCES compras_carrito(id);
CREATE TABLE constancia_detalles (
 operacion VARCHAR(120) NOT NULL REFERENCES constancias_compra(operacion),
 orden_id BIGINT NOT NULL REFERENCES ordenes_compra(id),
 curso_id BIGINT NOT NULL, docente_id BIGINT NOT NULL,
 titulo VARCHAR(180) NOT NULL, importe NUMERIC(10,2) NOT NULL,
 PRIMARY KEY(operacion,orden_id)
);
