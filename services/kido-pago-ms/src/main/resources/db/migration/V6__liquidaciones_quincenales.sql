ALTER TABLE ordenes_certificado ADD COLUMN costo_procesamiento NUMERIC(12,2), ADD COLUMN neto_recibido NUMERIC(12,2), ADD COLUMN fondos_estado VARCHAR(40), ADD COLUMN fecha_conciliacion TIMESTAMP;
ALTER TABLE movimientos_saldo ADD COLUMN conciliado BOOLEAN NOT NULL DEFAULT FALSE;
CREATE TABLE saldo_docente_bloqueos(docente_id BIGINT PRIMARY KEY);
CREATE TABLE liquidaciones_docente(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, docente_id BIGINT NOT NULL,
 desde DATE NOT NULL, corte DATE NOT NULL, estado VARCHAR(20) NOT NULL,
 monto NUMERIC(12,2) NOT NULL CHECK(monto>0), base_acumulada NUMERIC(12,2) NOT NULL,
 compromisos_anteriores NUMERIC(12,2) NOT NULL, movimiento_id BIGINT NOT NULL,
 fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL, fecha_pago TIMESTAMP WITH TIME ZONE,
 banco VARCHAR(120), codigo_operacion VARCHAR(120), fecha_operacion DATE,
 destino VARCHAR(160), titular VARCHAR(180), verificado_por VARCHAR(100), motivo_anulacion VARCHAR(300),
 constancia_tipo VARCHAR(40), constancia_sha256 VARCHAR(64)
);
CREATE UNIQUE INDEX uk_liquidacion_activa ON liquidaciones_docente(docente_id,corte) WHERE estado <> 'ANULADA';
CREATE UNIQUE INDEX uk_transferencia_liquidacion ON liquidaciones_docente(banco,fecha_operacion,codigo_operacion) WHERE estado='PAGADA';
CREATE TABLE liquidacion_detalles(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, liquidacion_id BIGINT NOT NULL REFERENCES liquidaciones_docente(id),
 movimiento_id BIGINT NOT NULL, concepto VARCHAR(300) NOT NULL, importe NUMERIC(12,2) NOT NULL,
 UNIQUE(liquidacion_id,movimiento_id)
);
