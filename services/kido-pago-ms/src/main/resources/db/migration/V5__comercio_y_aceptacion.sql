CREATE TABLE configuracion_comercial (
 id BIGINT PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
 razon_social VARCHAR(180) NOT NULL DEFAULT '', ruc VARCHAR(11) NOT NULL DEFAULT '',
 direccion VARCHAR(300) NOT NULL DEFAULT '', email_soporte VARCHAR(160) NOT NULL DEFAULT '',
 terminos TEXT NOT NULL DEFAULT '', privacidad TEXT NOT NULL DEFAULT '', reembolsos TEXT NOT NULL DEFAULT '',
 reclamaciones_url VARCHAR(500) NOT NULL DEFAULT '', publicada BOOLEAN NOT NULL DEFAULT FALSE
);
