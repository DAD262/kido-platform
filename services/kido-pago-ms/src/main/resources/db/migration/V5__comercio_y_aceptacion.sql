CREATE TABLE aceptaciones_compra (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tipo VARCHAR(20) NOT NULL, orden_id BIGINT NOT NULL, estudiante_id BIGINT NOT NULL,
 sujeto VARCHAR(100) NOT NULL, version_comercial BIGINT NOT NULL,
 fecha TIMESTAMP WITH TIME ZONE NOT NULL, texto_aceptado TEXT NOT NULL,
 UNIQUE(tipo,orden_id,sujeto,version_comercial)
);
